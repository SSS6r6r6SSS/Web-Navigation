const DefaultIcon = ({ label }: { label: string }) => (
  <span className="text-sm font-bold">{label.charAt(0).toUpperCase()}</span>
);

interface SocialLink {
  id: number;
  platform: string;
  url: string;
  icon: string;
  color: string;
}

interface SocialButtonsProps {
  links: SocialLink[];
}

export function SocialButtons({ links }: SocialButtonsProps) {
  if (!links.length) return null;

  return (
    <div className="mt-6 fade-in w-full max-w-2xl px-2">
      <div className="social-glass rounded-2xl px-4 py-3 sm:px-6 sm:py-4">
        <div className="flex flex-wrap justify-center gap-2">
          {links.map(link => {
            const iconKey = (link.icon || link.platform).toLowerCase().trim();
            const icon = SOCIAL_ICON_MAP[iconKey];
            const bgColor = link.color || '#0288d1';

            return (
              <a
                key={link.id}
                href={link.url}
                target="_blank"
                rel="noopener noreferrer"
                title={link.platform}
                className="social-btn"
                style={{ backgroundColor: bgColor }}
              >
                {icon ?? <DefaultIcon label={link.platform} />}
                <span className="hidden sm:inline">{link.platform}</span>
              </a>
            );
          })}
        </div>
      </div>
    </div>
  );
}
